def escape_pdf(text):
    return text.replace("\\", "\\\\").replace("(", "\\(").replace(")", "\\)")


def make_pages():
    pages = []
    current = []
    lines_left = 46

    def flush():
        nonlocal current, lines_left
        if current:
            pages.append(current)
        current = []
        lines_left = 46

    for heading, paragraphs in SECTIONS:
        if lines_left < 5:
            flush()
        current.append(("heading", heading))
        lines_left -= 2
        for paragraph in paragraphs:
            wrapped = textwrap.wrap(paragraph, width=102)
            if not wrapped:
                wrapped = [""]
            if lines_left < len(wrapped) + 2:
                flush()
                current.append(("heading", heading + " (continued)"))
                lines_left -= 2
            current.append(("body", wrapped[0]))
            for line in wrapped[1:]:
                current.append(("body", line))
            current.append(("body", ""))
            lines_left -= len(wrapped) + 1
    flush()
    return pages


def build_pdf(path):
    pages = make_pages()
    objects = []

    def add_object(content):
        objects.append(content)
        return len(objects)

    font_regular = add_object("<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>")
    font_bold = add_object("<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>")
    page_ids = []

    for page_number, page_lines in enumerate(pages, start=1):
        commands = [
            "BT",
            "/F2 18 Tf",
            "54 760 Td",
            f"({escape_pdf('Banking Anomaly Chatbot - Interview Guide')}) Tj",
            "0 -24 Td",
            "/F1 9 Tf",
        ]
        for kind, line in page_lines:
            if kind == "heading":
                commands.extend([
                    "/F2 12 Tf",
                    "0 -18 Td",
                    f"({escape_pdf(line)}) Tj",
                    "/F1 9 Tf",
                    "0 -15 Td",
                ])
            else:
                commands.append(f"({escape_pdf(line)}) Tj")
                commands.append("0 -12 Td")
        commands.extend([
            "/F1 8 Tf",
            "0 -8 Td",
            f"({escape_pdf(f'Page {page_number} of {len(pages)}')}) Tj",
            "ET",
        ])
        stream = "\n".join(commands).encode("latin-1", "replace")
        content_id = add_object(
            f"<< /Length {len(stream)} >>\nstream\n".encode("latin-1")
            + stream
            + b"\nendstream"
        )
        page_ids.append((content_id, page_number))

    pages_id = len(objects) + 1
    page_objects = []
    for content_id, _ in page_ids:
        page_objects.append(
            add_object(
                f"<< /Type /Page /Parent {pages_id} 0 R "
                f"/MediaBox [0 0 612 792] /Resources << /Font << "
                f"/F1 {font_regular} 0 R /F2 {font_bold} 0 R >> >> "
                f"/Contents {content_id} 0 R >>"
            )
        )
    objects.append(
        f"<< /Type /Pages /Kids [{' '.join(f'{page_id} 0 R' for page_id in page_objects)}] "
        f"/Count {len(page_objects)} >>"
    )
    catalog_id = add_object(f"<< /Type /Catalog /Pages {pages_id} 0 R >>")

    output = bytearray(b"%PDF-1.4\n%\xe2\xe3\xcf\xd3\n")
    offsets = [0]
    for index, obj in enumerate(objects, start=1):
        offsets.append(len(output))
        output.extend(f"{index} 0 obj\n".encode("latin-1"))
        if isinstance(obj, bytes):
            output.extend(obj)
        else:
            output.extend(obj.encode("latin-1"))
        output.extend(b"\nendobj\n")
    xref = len(output)
    output.extend(f"xref\n0 {len(objects) + 1}\n".encode("latin-1"))
    output.extend(b"0000000000 65535 f \n")
    for offset in offsets[1:]:
        output.extend(f"{offset:010d} 00000 n \n".encode("latin-1"))
    output.extend(
        f"trailer\n<< /Size {len(objects) + 1} /Root {catalog_id} 0 R >>\n"
        f"startxref\n{xref}\n%%EOF\n".encode("latin-1")
    )
    path.write_bytes(output)


if __name__ == "__main__":
    build_pdf(OUTPUT)
